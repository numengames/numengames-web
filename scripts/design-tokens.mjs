// Design tokens → src/styles/tokens.css
//
// The source of every colour, font family, radius and curve below is the
// installed package @numengames/design-kit (numinia-archive,
// machine/packages/design-kit/, STD-023). This script reads its token file
// and writes the CSS custom properties the site already consumed by hand —
// same variable names, same values, no longer hand-typed. Nothing here is
// typed by hand: STD-008 DSN-009 — the kit is installed, never copied.
// Spacing, type scale and z-index are this site's own (not in the kit) and
// stay hand-authored below.
//
//   node scripts/design-tokens.mjs           # write src/styles/tokens.css
//   node scripts/design-tokens.mjs --check   # exit 1 if the file is stale
//
// Runs as `pretest`/`prebuild`, so a bumped package regenerates the file and
// a hand edit is overwritten on the next build.

import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const TOKENS_PATH = require.resolve("@numengames/design-kit/sistema.tokens.json");
const PKG = JSON.parse(fs.readFileSync(path.join(path.dirname(TOKENS_PATH), "package.json"), "utf8"));
const OUT = path.resolve("src/styles/tokens.css");
const CHECK = process.argv.includes("--check");

const t = JSON.parse(fs.readFileSync(TOKENS_PATH, "utf8"));
const get = (p) => {
	const node = p.split(".").reduce((o, k) => (o == null ? undefined : o[k]), t);
	if (node == null || node.$value === undefined) throw new Error(`token missing: ${p}`);
	return node.$value;
};
const fontStack = (p) =>
	get(p)
		.map((f) => (f.includes(" ") ? `"${f}"` : f))
		.join(", ");
const hex = (p) => get(p).toLowerCase();

/* CSS variable ← kit token path. The left side is this site's own
   vocabulary (used across src/**); the right side is the kit's. */
const COLORS_NOCTURNO = {
	"--color-carbon": "color.nocturno.fondo-base",
	"--color-carbon-raised": "color.nocturno.fondo-superficie",
	"--color-carbon-elevated": "color.nocturno.fondo-elevada",
	"--color-marfil": "color.marca.arena",
	"--color-marfil-velada": "color.nocturno.texto-secundario",
	"--color-ceniza": "color.nocturno.texto-terciario",
	"--color-linea": "color.nocturno.linea-tenue",
	"--color-linea-fuerte": "color.nocturno.linea-fuerte",
	"--color-dorado": "color.marca.ambar",
	"--color-turquesa": "color.marca.turquesa",
	"--color-verdemar": "color.marca.verdemar",
	"--color-accion": "color.interactivo.fondo",
	"--color-accion-hover": "color.interactivo.hover",
	"--color-accion-activo": "color.interactivo.activo",
	"--color-alerta": "color.marca.coral",
	// Day-only colours, kept here as they are kit values too.
	"--color-dorado-texto-claro": "color.texto-sobre-claro.ambar",
	"--color-turquesa-texto-claro": "color.texto-sobre-claro.turquesa",
	"--color-alerta-claro": "color.texto-sobre-claro.grana",
	"--color-papel-superficie": "color.diurno.fondo-superficie",
	"--color-papel-linea": "color.diurno.linea-tenue",
	"--color-tinta-2": "color.diurno.texto-secundario",
	"--color-tinta-3": "color.diurno.texto-terciario",
};
// --color-blanco (text on the primary button) has no kit path of its own:
// it is plain white, independent of the palette.
const COLOR_BLANCO = "#ffffff";

let css = `/* ============================================================
   NUMEN GAMES — Design tokens
   ============================================================
   GENERATED by scripts/design-tokens.mjs from @numengames/design-kit
   ${PKG.version} (numinia-archive, machine/packages/design-kit/, STD-023).
   Do not hand-edit the colours, fonts, radii or curve below: bump the
   package and rerun the script. Spacing, type scale and z-index are this
   site's own and stay hand-authored (see the tail of this file).

   CONTRASTE. Todos los pares texto/superficie en uso cumplen WCAG
   2.1 AA (>= 4.5:1 para texto normal), verificado por cálculo de
   luminancia relativa en scripts/check-contrast.mjs, que corre en
   \`pnpm test\`. La tinta terciaria del kit (#8A7D72) solo pasa AA
   sobre el fondo (4.71:1; 4.33 y 3.84 sobre las superficies), así que
   de noche el texto apagado usa la secundaria (#C4B5A6). Los errores
   usan Coral de noche y Grana-texto de día.
   ============================================================ */

:root {
	/* ---- Paleta base (STD-023 §2), del kit instalado --------- */
`;
for (const [v, p] of Object.entries(COLORS_NOCTURNO)) css += `\t${v}: ${hex(p)}; /* ${p} */\n`;
css += `\t--color-blanco: ${COLOR_BLANCO}; /* texto sobre el botón primario — fuera de paleta */\n`;

css += `
	/* ---- Tema (noche por defecto, día opcional) ----------------- */
	--surface: var(--color-carbon);
	--surface-raised: var(--color-carbon-raised);
	--surface-elevated: var(--color-carbon-elevated);
	--ink: var(--color-marfil);
	--ink-muted: var(--color-marfil-velada);
	--ink-faint: var(--color-marfil-velada);
	--line: var(--color-linea);
	--line-strong: var(--color-linea-fuerte);
	--interactive: var(--color-verdemar);
	--accent: var(--color-dorado);
	--action: ${hex("color.interactivo.fondo")};
	--action-hover: var(--color-accion-hover);
	--action-active: var(--color-accion-activo);
	--action-ink: var(--color-blanco);
	--focus-ring: var(--color-turquesa);
	--underline-active: var(--color-turquesa);
	--alerta: var(--color-alerta);

	/* ---- Tipografía (STD-023 §8), familia del kit instalado -----
     Geist y Geist Mono autoalojadas (@fontsource-variable, importadas
     en SiteLayout), con los respaldos canónicos del sistema. */
	--font-titular: ${fontStack("fontFamily.sans").replace(/^Geist\b/, '"Geist Variable"')};
	--font-cuerpo: ${fontStack("fontFamily.sans").replace(/^Geist\b/, '"Geist Variable"')};
	--font-mono: ${fontStack("fontFamily.mono").replace('"Geist Mono"', '"Geist Mono Variable"')};

	--text-label: 0.7rem; /* etiqueta: Mono, mayúsculas, espaciada */
	--text-xs: 0.8rem;
	--text-sm: 0.9rem;
	--text-base: 1.125rem; /* ~18px */
	--text-lg: 1.35rem;
	--text-xl: clamp(1.6rem, 1.3rem + 1.2vw, 2.1rem);
	--text-2xl: clamp(2rem, 1.5rem + 2vw, 2.75rem);
	--text-3xl: clamp(2.25rem, 1.6rem + 2.6vw, 3.75rem);

	--leading-tight: 1.15;
	--leading-normal: 1.55;
	--measure: 66ch;

	/* ---- Espacio -------------------------------------------------
     Columna de 1100 px con 24 px a los lados, como numinia.org
     (STD-023 §23). */
	--content-max: 1100px;
	--space-2: 0.5rem;
	--space-3: 0.75rem;
	--space-4: 1rem;
	--space-6: 1.5rem;
	--space-8: 2rem;
	--space-12: 3rem;
	--space-16: 4rem;
	--space-24: 6rem;
	--gutter-mobile: 24px;

	/* ---- Radios (STD-023 §9): dos, y ninguno más, del kit -------- */
	--radius-control: ${get("borderRadius.control")}; /* borderRadius.control */
	--radius-frame: ${get("borderRadius.marco")}; /* borderRadius.marco */

	/* ---- Movimiento (STD-023 §14), curva del kit ----------------- */
	--ease-out: cubic-bezier(${get("cubicBezier.ciclo").join(", ")}); /* cubicBezier.ciclo */
	--dur-fast: 150ms;
	--dur-normal: 250ms;

	--z-header: 50;
	--z-notice: 70;
}

/* ---- Modo Diurno (DSN-016) ---------------------------------------
   The house switch writes data-modo on <html>; its absence means
   Nocturno, the default above. Same key and attribute as numinia.com. */
[data-modo="diurno"] {
	--surface: var(--color-marfil);
	--surface-raised: var(--color-papel-superficie);
	--surface-elevated: var(--color-papel-superficie);
	--ink: var(--color-carbon);
	--ink-muted: var(--color-tinta-2);
	--ink-faint: var(--color-tinta-3);
	--line: var(--color-papel-linea);
	--line-strong: var(--color-marfil-velada);
	--interactive: var(--color-turquesa-texto-claro);
	--accent: var(--color-dorado-texto-claro);
	--focus-ring: var(--color-turquesa-texto-claro);
	--underline-active: var(--color-turquesa-texto-claro);
	--alerta: var(--color-alerta-claro);
}

@media (prefers-reduced-motion: reduce) {
	:root {
		--dur-fast: 0ms;
		--dur-normal: 0ms;
	}
}
`;

if (CHECK) {
	const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
	if (cur !== css) {
		console.error(`design-tokens: ${path.relative(".", OUT)} is stale — run node scripts/design-tokens.mjs`);
		process.exit(1);
	}
	console.log(`design-tokens: ${path.relative(".", OUT)} matches @numengames/design-kit ${PKG.version}.`);
} else {
	fs.writeFileSync(OUT, css);
	console.log(`design-tokens: wrote ${path.relative(".", OUT)} from @numengames/design-kit ${PKG.version}.`);
}
